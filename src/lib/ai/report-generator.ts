/**
 * Generates all 27 report sections by iterating over ALL_SECTION_TYPES.
 * The AI response is safely converted to Markdown — no more [object Object].
 */
export async function generateReportSections(
  analysis: RepositoryAnalysis
): Promise<ReportSection[]> {
  const ai = getAIProvider()
  const sections: ReportSection[] = []

  for (const sectionType of ALL_SECTION_TYPES) {
    let content = ''

    try {
      const prompt = reportPrompt(sectionType, analysis, [])
      const raw = await ai.complete(prompt)
      content = safeToMarkdown(raw)
    } catch {
      // Network / API error — use fallback immediately
    }

    // If AI returned empty or object → use rich fallback
    if (!content || content.trim().length < 30) {
      content = generateFallbackContent(sectionType, analysis)
    }

    sections.push({
      id: randomUUID(),
      type: sectionType,
      title: SECTION_TITLES[sectionType],
      content,
      version: 1,
      updatedAt: new Date(),
    })
  }

  return sections
}

/**
 * Regenerates a single section with an optional instruction.
 */
export async function regenerateSection(
  sectionType: SectionType,
  analysis: RepositoryAnalysis,
  instruction?: string
): Promise<ReportSection> {
  const ai = getAIProvider()
  let content = ''

  try {
    let prompt = reportPrompt(sectionType, analysis, [])
    if (instruction) {
      prompt += `\n\nAdditional instruction: ${instruction}`
    }
    const raw = await ai.complete(prompt)
    content = safeToMarkdown(raw)
  } catch {
    content = ''
  }

  if (!content || content.trim().length < 30) {
    content = generateFallbackContent(sectionType, analysis)
  }

  return {
    id: randomUUID(),
    type: sectionType,
    title: SECTION_TITLES[sectionType],
    content,
    version: 1,
    updatedAt: new Date(),
  }
}
