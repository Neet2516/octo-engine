/** Safely stringify any value returned from AI into a proper Markdown string */
function safeToMarkdown(raw: unknown): string {
  if (typeof raw === 'string') {
    const trimmed = raw.trim()
    if (trimmed.length > 0) return trimmed
    return ''
  }
  // If AI returned a parsed object, render it as readable YAML-like markdown
  if (typeof raw === 'object' && raw !== null) {
    const obj = raw as Record<string, unknown>
    const lines: string[] = []
    for (const [key, value] of Object.entries(obj)) {
      const label = key.replace(/_/g, ' ').replace(/([A-Z])/g, ' $1').trim()
      if (Array.isArray(value)) {
        lines.push(`**${label}:**`)
        for (const item of value) {
          if (typeof item === 'string') {
            lines.push(`- ${item}`)
          } else if (typeof item === 'object' && item !== null) {
            const sub = item as Record<string, unknown>
            const name = sub.name || sub.mechanism || sub.method || Object.values(sub)[0]
            const desc = sub.description || sub.responsibility || sub.path || ''
            lines.push(`- **${name}**${desc ? `: ${desc}` : ''}`)
          }
        }
      } else if (typeof value === 'string' && value.trim()) {
        lines.push(`**${label}:** ${value}`)
      } else if (typeof value === 'number' || typeof value === 'boolean') {
        lines.push(`**${label}:** ${value}`)
      }
    }
    return lines.join('\n')
  }
  return ''
}

